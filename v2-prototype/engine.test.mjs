import assert from 'node:assert/strict';
import {initialState,balance,receiveGoods,reverseGoodsReceipt,createPurchase,savePurchase,unmatchedQty,postMovement,correctReceipt,suggestedReceipts,selectedReceiptQuantity,commonSupplierReference} from './engine.mjs';
const st=initialState();
assert.equal(balance(st,'HCSSP01'),8);
const r=receiveGoods(st,{itemCode:'HCSSP01',qty:20,requestId:'req-1',supplierDoc:'INV-01'});
assert.equal(balance(st,'HCSSP01'),28);
assert.equal(receiveGoods(st,{itemCode:'HCSSP01',qty:20,requestId:'req-1'}).duplicate,true);
assert.equal(balance(st,'HCSSP01'),28);
const p=createPurchase(st,{supplier:'Supplier A',invoice:'INV-01',itemCode:'HCSSP01',invoiceQty:20,unitCost:22000,receiptAllocations:[{receiptId:r.receipt.id,qty:20}]});
assert.equal(p.status,'MATCHED');assert.equal(balance(st,'HCSSP01'),28);assert.equal(unmatchedQty(st,r.receipt.id),0);
postMovement(st,{itemCode:'HCSSP01',qty:5,type:'MATERIAL_ISSUE',requestId:'req-2'});
assert.equal(balance(st,'HCSSP01'),23);
const p2=createPurchase(st,{supplier:'Supplier B',invoice:'INV-02',itemCode:'PEKM03',invoiceQty:2,unitCost:10});
assert.equal(p2.status,'PENDING MATCHING');assert.equal(balance(st,'PEKM03'),1);
assert.throws(()=>postMovement(st,{itemCode:'PEKM03',qty:2,type:'MATERIAL_ISSUE',requestId:'req-3'}),/Insufficient/);
assert.throws(()=>createPurchase(st,{supplier:'Supplier C',invoice:'INV-03',itemCode:'HCSSP01',invoiceQty:20,unitCost:10,receiptAllocations:[{receiptId:r.receipt.id,qty:20}]}),/exceeds available/);
const st2=initialState();
const r2=receiveGoods(st2,{itemCode:'HCSSP01',qty:20,requestId:'req-2a'});
const partial=createPurchase(st2,{supplier:'Supplier A',invoice:'INV-04',itemCode:'HCSSP01',invoiceQty:30,unitCost:12,receiptAllocations:[{receiptId:r2.receipt.id,qty:20}]});
assert.equal(partial.status,'PARTIALLY MATCHED');
assert.equal(balance(st2,'HCSSP01'),28);
const fixed=savePurchase(st2,{id:partial.id,supplier:'Supplier A',invoice:'INV-04',itemCode:'HCSSP01',invoiceQty:20,unitCost:12,receiptAllocations:[{receiptId:r2.receipt.id,qty:20}]});
assert.equal(fixed.status,'MATCHED');assert.equal(st2.purchases.length,1);assert.equal(balance(st2,'HCSSP01'),28);
const r3=receiveGoods(st2,{itemCode:'HCSSP01',qty:30,requestId:'req-3a'});
assert.equal(balance(st2,'HCSSP01'),58);
correctReceipt(st2,{receiptId:r3.receipt.id,correctQty:20,reason:'Counted ten too many'});
assert.equal(balance(st2,'HCSSP01'),48);assert.equal(st2.corrections.length,1);
assert.throws(()=>correctReceipt(st2,{receiptId:r2.receipt.id,correctQty:10,reason:'Mistake'}),/already matched/);
const st3=initialState();
const matchOne=receiveGoods(st3,{itemCode:'HCSSP01',qty:20,supplierDoc:'  INV-2026-001 ',requestId:'staff-1'});
receiveGoods(st3,{itemCode:'HCSSP01',qty:5,supplierDoc:'DIFFERENT',requestId:'staff-2'});
assert.deepEqual(suggestedReceipts(st3,{invoice:'inv-2026-001',itemCode:'HCSSP01'}).map(r=>r.id),[matchOne.receipt.id]);
assert.equal(suggestedReceipts(st3,{invoice:'',itemCode:'HCSSP01'}).length,0);
const matched=createPurchase(st3,{supplier:'A',invoice:'INV-2026-001',itemCode:'HCSSP01',invoiceQty:20,unitCost:1,receiptAllocations:[{receiptId:matchOne.receipt.id,qty:20}]});
assert.equal(matched.status,'MATCHED');assert.equal(suggestedReceipts(st3,{invoice:'INV-2026-001',itemCode:'HCSSP01'}).length,0);
assert.equal(selectedReceiptQuantity(st3,[matchOne.receipt.id],matched.id),20);
assert.equal(selectedReceiptQuantity(st3,[matchOne.receipt.id],null),0);
const st4=initialState();
const a=receiveGoods(st4,{itemCode:'HCSSP01',qty:12,requestId:'multi-1'});
const b=receiveGoods(st4,{itemCode:'HCSSP01',qty:8,requestId:'multi-2'});
assert.equal(selectedReceiptQuantity(st4,[a.receipt.id,b.receipt.id]),20);
assert.equal(selectedReceiptQuantity(st4,[a.receipt.id,a.receipt.id]),12);
const st5=initialState();
const refA=receiveGoods(st5,{itemCode:'HCSSP01',qty:12,supplierDoc:' INV-77 ',requestId:'ref-a'});
const refB=receiveGoods(st5,{itemCode:'HCSSP01',qty:8,supplierDoc:'inv-77',requestId:'ref-b'});
const refC=receiveGoods(st5,{itemCode:'HCSSP01',qty:5,supplierDoc:'INV-88',requestId:'ref-c'});
assert.equal(commonSupplierReference(st5,[refA.receipt.id,refB.receipt.id]),'INV-77');
assert.equal(commonSupplierReference(st5,[refA.receipt.id,refC.receipt.id]),null);
assert.equal(suggestedReceipts(st5,{invoice:'INV-77',itemCode:'HCSSP01'}).length,2);
// User's exact regression: wrong supplier invoice saved without checking a receipt;
// edit the same purchase to correct the invoice number and save without a checkbox.
const st6=initialState();
const realReceipt=receiveGoods(st6,{itemCode:'HCSSP01',qty:20,supplierDoc:'TRUE-INV',requestId:'real-1'});
const badInvoice=savePurchase(st6,{supplier:'Supplier A',invoice:'WRONG-INV',itemCode:'HCSSP01',invoiceQty:20,unitCost:100,autoMatch:true});
assert.equal(badInvoice.status,'PENDING MATCHING');
const corrected=savePurchase(st6,{id:badInvoice.id,supplier:'Supplier A',invoice:'TRUE-INV',itemCode:'HCSSP01',invoiceQty:20,unitCost:100,autoMatch:true});
assert.equal(corrected.status,'MATCHED');
assert.equal(corrected.receiptAllocations[0].receiptId,realReceipt.receipt.id);
assert.equal(st6.purchases.length,1);assert.equal(balance(st6,'HCSSP01'),28);
// Explicit manual override may still leave a purchase unmatched.
const st7=initialState();
receiveGoods(st7,{itemCode:'HCSSP01',qty:20,supplierDoc:'INV-7',requestId:'real-7'});
const manual=savePurchase(st7,{supplier:'Supplier A',invoice:'INV-7',itemCode:'HCSSP01',invoiceQty:20,unitCost:100,autoMatch:false});
assert.equal(manual.status,'PENDING MATCHING');
// User regression: wrong item physically recorded under invoice 1111, then KELUAR
// with the same item/reference must remove the receipt from owner matching too.
const st8=initialState();
const wrong=receiveGoods(st8,{itemCode:'PEKM03',qty:1,supplierDoc:'1111',requestId:'wrong-in'});
assert.equal(balance(st8,'PEKM03'),2);
assert.equal(suggestedReceipts(st8,{invoice:'1111',itemCode:'PEKM03'}).length,1);
const reversal=reverseGoodsReceipt(st8,{itemCode:'PEKM03',qty:1,supplierDoc:'1111',requestId:'wrong-out'});
assert.equal(reversal.reversedQty,1);
assert.equal(balance(st8,'PEKM03'),1);
assert.equal(unmatchedQty(st8,wrong.receipt.id),0);
assert.equal(wrong.receipt.status,'REVERSED');
assert.equal(suggestedReceipts(st8,{invoice:'1111',itemCode:'PEKM03'}).length,0);
assert.equal(reverseGoodsReceipt(st8,{itemCode:'PEKM03',qty:1,supplierDoc:'1111',requestId:'wrong-out'}).duplicate,true);
assert.equal(balance(st8,'PEKM03'),1);
assert.throws(()=>reverseGoodsReceipt(st8,{itemCode:'PEKM03',qty:1,supplierDoc:'1111',requestId:'wrong-out-2'}),/no sufficient unmatched/);
const st9=initialState();
const partialReceipt=receiveGoods(st9,{itemCode:'HCSSP01',qty:20,supplierDoc:'1111',requestId:'pr-in'});
savePurchase(st9,{supplier:'S',invoice:'1111',itemCode:'HCSSP01',invoiceQty:15,unitCost:1,receiptAllocations:[{receiptId:partialReceipt.receipt.id,qty:15}]});
assert.throws(()=>reverseGoodsReceipt(st9,{itemCode:'HCSSP01',qty:10,supplierDoc:'1111',requestId:'pr-out'}),/no sufficient unmatched/);
assert.equal(balance(st9,'HCSSP01'),28);
console.log('PASS: receipt, duplicate prevention, purchasing no stock impact, edit partial match, physical correction, and guardrails');
